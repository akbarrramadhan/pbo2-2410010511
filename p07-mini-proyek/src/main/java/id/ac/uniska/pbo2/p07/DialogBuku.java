    private void simpanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanButtonActionPerformed
        // TODO add your handling code here:
        String kode = kodeField.getText().trim();
        String judul = judulField.getText().trim();
        String penulis = penulisField.getText().trim();
        String tahunText = tahunField.getText().trim();

        // Validasi kode dan judul
        if (kode.isEmpty() || judul.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Kode dan judul wajib diisi!"
            );
            return;
        }

        // Validasi tahun
        int tahun;

        try {
            tahun = Integer.parseInt(tahunText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Tahun harus berupa angka!"
            );
            return;
        }

        int tahunSekarang
                = java.time.Year.now().getValue();

        if (tahun < 1900 || tahun > tahunSekarang) {
            JOptionPane.showMessageDialog(
                    this,
                    "Tahun harus antara 1900 sampai "
                    + tahunSekarang
            );
            return;
        }

        if (penulis.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Nama penulis wajib diisi!"
            );
            return;
        }

        // Membuat objek buku baru
        Buku buku = new Buku(
                kode, judul, tahun, penulis
        );

        // Mengatur status buku
        String status = statusCombo.getSelectedItem().toString();

        if (status.equals("Dipinjam")) {
            buku.pinjam();
        }

        hasil = buku;
        berhasil = true;

        dispose();
    }//GEN-LAST:event_simpanButtonActionPerformed

