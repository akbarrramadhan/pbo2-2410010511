    private void ubahButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ubahButtonActionPerformed
        // TODO add your handling code here:
        int baris = katalogTable.getSelectedRow();

    if (baris == -1) {

        JOptionPane.showMessageDialog(
            this,
            "Pilih buku yang ingin diubah!"
        );

        return;
    }

    int modelRow =
        katalogTable.convertRowIndexToModel(baris);

    Buku buku =
        modelBuku.getBukuAt(modelRow);

    DialogBuku dialog = new DialogBuku(
        this,
        "Ubah Buku",
        buku
    );

    dialog.setVisible(true);

    if (dialog.isBerhasil()) {

        modelBuku.ubahBuku(
            modelRow,
            dialog.getHasil()
        );

        updateStatus();

        JOptionPane.showMessageDialog(
            this,
            "Data buku berhasil diubah!"
        );
    }
    }//GEN-LAST:event_ubahButtonActionPerformed

    private void hapusButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hapusButtonActionPerformed
        // TODO add your handling code here:
        int baris = katalogTable.getSelectedRow();

    if (baris == -1) {

        JOptionPane.showMessageDialog(
            this,
            "Pilih buku yang ingin dihapus!"
        );

        return;
    }

    int konfirmasi =
        JOptionPane.showConfirmDialog(
            this,
            "Apakah Anda yakin ingin menghapus buku ini?",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION
        );

    if (konfirmasi == JOptionPane.YES_OPTION) {

        int modelRow =
            katalogTable.convertRowIndexToModel(baris);

        modelBuku.hapusBuku(modelRow);

        updateStatus();

        JOptionPane.showMessageDialog(
            this,
            "Buku berhasil dihapus!"
        );
    }
    }//GEN-LAST:event_hapusButtonActionPerformed

