    private void aturPencarian() {

        cariField.getDocument().addDocumentListener(
                new DocumentListener() {

            @Override
            public void insertUpdate(DocumentEvent e) {
                cariBuku();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                cariBuku();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                cariBuku();
            }
        }
        );
    }
    private void cariBuku() {

    String keyword =
            cariField.getText().trim();

    if (keyword.isEmpty()) {

        sorter.setRowFilter(null);

    } else {

        sorter.setRowFilter(
            RowFilter.regexFilter(
                "(?i)" + Pattern.quote(keyword),
                0, 1, 2
            )
        );
    }

    updateStatus();
}



private void updateStatus() {

    int jumlahDitampilkan =
            katalogTable.getRowCount();

    int jumlahTersedia = 0;

    for (int i = 0; i < katalogTable.getRowCount(); i++) {

        Object status =
                katalogTable.getValueAt(i, 4);

        if (status != null &&
            status.toString().equals("Tersedia")) {

            jumlahTersedia++;
        }
    }

    statusLabel.setText(
        "Jumlah buku ditampilkan: "
        + jumlahDitampilkan
        + " | Buku tersedia: "
        + jumlahTersedia
    );
}


private void aturPilihanTabel() {

    katalogTable.getSelectionModel()
        .addListSelectionListener(e -> {

            if (!e.getValueIsAdjusting()) {

                boolean dipilih =
                    katalogTable.getSelectedRow() != -1;

                ubahButton.setEnabled(dipilih);
                hapusButton.setEnabled(dipilih);
            }
        });
}

